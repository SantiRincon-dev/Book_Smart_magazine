#!/usr/bin/env python3
"""Builds the small display-font files that single issues use for their headline.

Why separate from css/fonts.css? These faces are used by ONE page for ONE
headline, so they must not weigh on every other page. Google Fonts can serve a
face already trimmed to the glyphs you ask for (the `text=` parameter), which
is a few KB. This script downloads that, embeds it as base64 (so it works from
a double click, for the same reason fonts.css does) and writes
css/issues/<issue>-fonts.css, which the issue's own stylesheet @imports.

Run it from the project root, only when an issue's headline font or text changes:

    python tools/make-issue-fonts.py

To give another issue a display face, add one entry to ISSUES below: the
family and weight as Google Fonts names them, and the characters the headline
may use. Letters, digits and the usual punctuation are included by default, so
retitling an issue does not need a rebuild unless it uses an unusual character.

Faces in use (all SIL Open Font License 1.1):
  UnifrakturCook (Week 04's newspaper nameplate, like the blackletter of its
  own infographic), by j. 'mach' wust.
"""
import base64
import re
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "css" / "issues"
UA = ("Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
      "(KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36")

# Letters, digits and the punctuation a headline may need.
DEFAULT_TEXT = ("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789"
                " &.,:;!?'\"()-–—…’‘“”")

ISSUES = {
    "w04": [
        # (css family name, Google Fonts family, weight, extra characters)
        ("UnifrakturCook", "UnifrakturCook", 700, ""),
    ],
}


def fetch(url):
    request = urllib.request.Request(url, headers={"User-Agent": UA})
    return urllib.request.urlopen(request, timeout=30).read()


def face(css_name, family, weight, extra):
    text = DEFAULT_TEXT + extra
    url = ("https://fonts.googleapis.com/css2?family=%s:wght@%d&text=%s&display=block"
           % (urllib.parse.quote(family), weight, urllib.parse.quote(text)))
    css = fetch(url).decode("utf-8")
    source = re.search(r"url\((https://[^)]+)\)\s*format\('woff2'\)", css)
    if not source:
        raise SystemExit("Google Fonts did not return a woff2 for %s %d" % (family, weight))
    data = fetch(source.group(1))
    encoded = base64.b64encode(data).decode("ascii")
    block = ('@font-face {\n  font-family: "%s";\n  font-style: normal;\n  font-weight: %d;\n'
             '  font-display: block;\n  src: url(data:font/woff2;base64,%s) format("woff2");\n}\n'
             % (css_name, weight, encoded))
    return block, len(data)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for issue, faces in ISSUES.items():
        parts = ["/* GENERATED by tools/make-issue-fonts.py: do not edit by hand.\n"
                 "   The display face(s) of Week %s, trimmed to the glyphs of a headline\n"
                 "   and embedded so the page works from a double click. */\n" % issue[1:]]
        for css_name, family, weight, extra in faces:
            block, size = face(css_name, family, weight, extra)
            parts.append(block)
            print("%s: %s %d  %d bytes" % (issue, css_name, weight, size))
        target = OUT / ("%s-fonts.css" % issue)
        target.write_text("".join(parts), encoding="utf-8", newline="\n")
        print("wrote %s (%d KB)" % (target.relative_to(ROOT), target.stat().st_size // 1024))


if __name__ == "__main__":
    main()
