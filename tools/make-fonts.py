#!/usr/bin/env python3
"""Builds css/fonts.css: the magazine's two typefaces, trimmed and embedded.

Why embedded? The site has to work when index.html is opened by double click
(file://). From a file:// page some browsers refuse to load font files that
live in another folder, so the fonts travel inside the stylesheet as base64
woff2 instead. The result is one request, no flash of fallback type.

What it does, per face:
  1. downloads Google Fonts' Latin woff2 (variable font);
  2. limits the variable axes to the range the design actually uses;
  3. drops every glyph outside Basic Latin, Latin-1 and typographic
     punctuation (the magazine is in English with a few Spanish names);
  4. writes an @font-face with the base64 data. font-display is "block": the
     data is already in the stylesheet, so the face is ready within
     milliseconds, and "swap" would only flash the fallback face.

Run it from the project root, only when a font or its axis range changes:

    python -m pip install fonttools brotli
    python tools/make-fonts.py

Both typefaces are SIL Open Font License 1.1: Anybody (Tyler Finck, Etcetera
Type Co) and Newsreader (Production Type).
"""
import base64
import io
import re
import urllib.request
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "css" / "fonts.css"
UA = ("Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
      "(KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36")

# Basic Latin, Latin-1 Supplement, a few Latin Extended letters and the
# typographic punctuation English text uses.
UNICODES = (
    list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) +
    [0x131, 0x152, 0x153, 0x160, 0x161, 0x178, 0x17D, 0x17E, 0x2C6, 0x2DA, 0x2DC,
     0x2013, 0x2014, 0x2018, 0x2019, 0x201A, 0x201C, 0x201D, 0x201E,
     0x2020, 0x2021, 0x2022, 0x2026, 0x2030, 0x2039, 0x203A, 0x20AC, 0x2122, 0x2212]
)
FEATURES = ["kern", "liga", "calt", "ccmp", "locl", "mark", "mkmk",
            "case", "tnum", "lnum", "onum", "pnum"]

FACES = [
    # Display face: wdth 62 is the condensed "sign painter" cut, 100 is the
    # normal-width cut used for small interface labels.
    dict(family="Anybody", style="normal",
         query="Anybody:wdth,wght@50..150,100..900",
         axes={"wdth": (62, 100), "wght": (500, 900)},
         css="font-weight: 500 900;\n  font-stretch: 62% 100%;"),
    # Reading face.
    # Google's file still carries the family's full 200-800 axis; 400-700 is
    # all the design uses (regular text, medium labels, bold emphasis).
    dict(family="Newsreader", style="normal",
         query="Newsreader:wght@400..700",
         axes={"wght": (400, 700)},
         css="font-weight: 400 700;"),
    dict(family="Newsreader", style="italic",
         query="Newsreader:ital,wght@1,400..700",
         axes={"wght": (400, 700)},
         css="font-weight: 400 700;"),
]


def fetch(url):
    request = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read()


def latin_url(css_text):
    """The woff2 URL of the plain `latin` block of a Google Fonts stylesheet."""
    for block in re.split(r"(?=/\* [a-z\-]+ \*/)", css_text):
        if block.startswith("/* latin */"):
            return re.search(r"src: url\((https://[^)]+)\)", block).group(1)
    raise RuntimeError("no latin block in the Google Fonts stylesheet")


def build(face):
    css = fetch(f"https://fonts.googleapis.com/css2?family={face['query']}&display=swap").decode()
    font = TTFont(io.BytesIO(fetch(latin_url(css))))

    # Subset first, then limit the axes: instancing a font that still has
    # every glyph and then subsetting it trips over glyphs without deltas.
    options = subset.Options()
    options.layout_features = FEATURES
    options.name_IDs = [1, 2, 3, 4, 6]
    options.notdef_outline = True
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=UNICODES)
    subsetter.subset(font)

    font = instancer.instantiateVariableFont(font, face["axes"])

    font.flavor = "woff2"
    buffer = io.BytesIO()
    font.save(buffer)
    return buffer.getvalue()


def main():
    chunks = [
        "/* GENERATED by tools/make-fonts.py. Do not edit by hand.\n"
        "   Anybody and Newsreader: SIL Open Font License 1.1.\n"
        "   Embedded as base64 so the site works from file:// (double click). */\n"
    ]
    for face in FACES:
        data = build(face)
        print(f"{face['family']:<11} {face['style']:<7} {len(data) / 1024:6.1f} KB")
        chunks.append(
            "@font-face {\n"
            f"  font-family: \"{face['family']}\";\n"
            f"  font-style: {face['style']};\n"
            f"  {face['css']}\n"
            "  font-display: block;\n"
            f"  src: url(data:font/woff2;base64,{base64.b64encode(data).decode()}) format(\"woff2\");\n"
            "}\n"
        )
    OUT.write_text("\n".join(chunks), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
